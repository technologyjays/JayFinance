def _chat_client():
    """Groq client for Chat Finance. AI Importer tetap memakai OpenAI sendiri."""
    if OpenAI is None:
        return None

    api_key = os.getenv("GROQ_API_KEY", "").strip()
    if not api_key:
        env_path = os.path.join(os.getcwd(), ".env")
        if os.path.exists(env_path):
            try:
                with open(env_path, "r", encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if line.startswith("GROQ_API_KEY="):
                            api_key = line.split("=", 1)[1].strip().strip('"').strip("'")
                            break
            except Exception:
                pass

    if not api_key:
        return None

    return OpenAI(
        api_key=api_key,
        base_url="https://api.groq.com/openai/v1"
    )


def _chat_normalize_platform(value):
    value = str(value or "").strip().lower()
    mapping = {
        "bca": "BCA", "sea bank": "SeaBank", "seabank": "SeaBank",
        "mandiri": "Mandiri", "cash": "Cash", "tunai": "Cash",
        "stockbit": "Bibit/Stockbit", "bibit": "Bibit/Stockbit",
        "bibit/stockbit": "Bibit/Stockbit", "lainnya": "Lainnya"
    }
    return mapping.get(value, str(value or "").strip())


def _chat_category(value, keterangan, tipe):
    v = str(value or "").strip()
    low = (v + " " + str(keterangan or "")).lower()
    if tipe == "Pemasukan":
        if any(x in low for x in ["gaji", "salary", "payroll"]): return "Gaji"
        if any(x in low for x in ["fee", "freelance", "job", "honor"]): return "Fee"
    if any(x in low for x in ["nasi", "makan", "minum", "kopi", "ayam", "mie", "gorengan", "restoran", "restaurant"]):
        return "Makanan & Minuman"
    if any(x in low for x in ["bensin", "pertalite", "pertamax", "solar", "fuel"]):
        return "Bensin"
    for c in CATEGORIES:
        if c.lower() == v.lower(): return c
    return "Lainnya"


def _chat_parse_message(message):
    client = _chat_client()
    if client is None:
        raise RuntimeError("GROQ_API_KEY belum tersedia atau package OpenAI belum terpasang. Buat API key Groq lalu simpan sebagai GROQ_API_KEY di file .env.")
    today = date.today().isoformat()
    instructions = (
        "Kamu adalah parser transaksi untuk aplikasi JayFinance Indonesia.\n"
        f"Tanggal hari ini: {today}.\n"
        f"Platform valid: {", ".join(PLATFORMS)}.\n"
        f"Kategori valid: {", ".join(CATEGORIES)}.\n\n"
        "Ubah chat singkat pengguna menjadi SATU transaksi JSON. Jangan mengarang data yang tidak ada.\n"
        "Aturan:\n"
        "- Jika tanggal tidak disebut, gunakan tanggal hari ini.\n"
        "- 10k, 10rb, 10 ribu = 10000. 1,5jt atau 1.5jt = 1500000.\n"
        "- pakai BCA, di BCA, dari BCA berarti platform BCA untuk transaksi biasa.\n"
        "- Default transaksi biasa adalah Pengeluaran. Jika jelas gaji masuk, dapat uang, bonus masuk, dll maka Pemasukan.\n"
        "- Jika ada transfer dari X ke Y, tipe Transfer dan isi dari_platform serta ke_platform.\n"
        "- Untuk makanan, kategori Makanan & Minuman dan catatan makanan.\n"
        "- Nama transaksi singkat dan natural, misalnya Nasi Goreng.\n"
        "- Jika nominal atau platform untuk transaksi biasa tidak jelas, perlu_konfirmasi=true dan jelaskan yang kurang. Jangan memasukkan transaksi yang perlu konfirmasi.\n"
        "- Output HANYA JSON valid dengan field: tanggal, keterangan, kategori, platform, tipe, nominal, dari_platform, ke_platform, catatan, perlu_konfirmasi, pesan_konfirmasi.\n"
    )
    response = client.chat.completions.create(
        model=CHAT_MODEL,
        messages=[
            {"role": "system", "content": instructions},
            {"role": "user", "content": message}
        ],
        response_format={"type": "json_object"},
        temperature=0
    )
    raw = (response.choices[0].message.content or "").strip()
    if raw.startswith("```"):
        raw = raw.replace("```json", "", 1).replace("```", "").strip()
    return json.loads(raw)


def _chat_insert_transaction(data):
    tanggal = clean_date(data.get("tanggal")) or date.today().isoformat()
    keterangan = str(data.get("keterangan") or "").strip()
    tipe = str(data.get("tipe") or "Pengeluaran").strip()
    nominal = parse_nominal(data.get("nominal"))
    platform = _chat_normalize_platform(data.get("platform"))
    dari_platform = _chat_normalize_platform(data.get("dari_platform"))
    ke_platform = _chat_normalize_platform(data.get("ke_platform"))
    kategori = _chat_category(data.get("kategori"), keterangan, tipe)
    catatan = str(data.get("catatan") or "").strip()

    if tipe == "Transfer":
        platform = ""
        kategori = "Transfer"
        if not dari_platform or not ke_platform:
            return {"ok": False, "message": "Transfer harus punya asal dan tujuan rekening."}
    else:
        dari_platform = ""
        ke_platform = ""
        if not platform:
            return {"ok": False, "message": "Platform belum jelas. Contoh: nasi goreng 10k pakai BCA."}
    if not keterangan or nominal <= 0:
        return {"ok": False, "message": "Keterangan atau nominal belum jelas."}
    if kategori == "Makanan & Minuman":
        catatan = "makanan"

    duplicate = find_duplicate(tanggal, keterangan, nominal, tipe, platform, dari_platform, ke_platform)
    if duplicate:
        return {"ok": False, "duplicate": True, "message": f"Transaksi serupa sudah ada: {duplicate['tanggal']} — {duplicate['keterangan']} — {rupiah(duplicate['nominal'])}."}

    backup_path = make_backup()
    conn = get_db()
    conn.execute("""
        INSERT INTO transaksi (tanggal, keterangan, kategori, platform, tipe, nominal, dari_platform, ke_platform)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
    """, (tanggal, keterangan, kategori, platform, tipe, nominal, dari_platform, ke_platform))
    conn.commit()
    new_id = conn.execute("SELECT currval(pg_get_serial_sequence('transaksi', 'id'))").fetchone()[0]
    conn.close()
    write_log({"action": "CHAT_IMPORT", "id": new_id, "backup": backup_path, "transaction": data})
