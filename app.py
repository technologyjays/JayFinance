def transaction_fingerprint(
    tanggal,
    keterangan,
    nominal,
    tipe,
    platform="",
    dari_platform="",
    ke_platform=""
):

    text = "|".join([
        clean_date(tanggal),
        str(keterangan or "").strip().lower(),
        str(int(nominal or 0)),
        str(tipe or "").strip().lower(),
        str(platform or "").strip().lower(),
        str(dari_platform or "").strip().lower(),
        str(ke_platform or "").strip().lower(),
    ])

    return hashlib.sha256(
        text.encode("utf-8")
    ).hexdigest()


def find_duplicate(
    tanggal,
    keterangan,
    nominal,
    tipe,
    platform="",
    dari_platform="",
    ke_platform=""
):

    conn = get_db()

    tanggal = clean_date(tanggal)

    # -----------------------------------------
    # Untuk transfer
    # -----------------------------------------

    if tipe == "Transfer":

        rows = conn.execute("""
            SELECT *
            FROM transaksi
            WHERE tanggal = %s
              AND nominal = %s
              AND tipe = 'Transfer'
        """, (
            tanggal,
            nominal
        )).fetchall()

    else:

        rows = conn.execute("""
            SELECT *
            FROM transaksi
            WHERE tanggal = %s
              AND nominal = %s
              AND tipe = %s
        """, (
            tanggal,
            nominal,
            tipe
        )).fetchall()

    conn.close()

    target_text = str(keterangan or "").strip().lower()

    for row in rows:

        existing_text = str(
            row["keterangan"] or ""
        ).strip().lower()

        # Cocok sangat kuat:
        # tanggal + nominal + tipe + platform + keterangan

        same_platform = (
            str(row["platform"] or "").lower()
            == str(platform or "").lower()
        )

        same_from = (
            str(row["dari_platform"] or "").lower()
            == str(dari_platform or "").lower()
        )

        same_to = (
            str(row["ke_platform"] or "").lower()
            == str(ke_platform or "").lower()
        )

        same_description = (
            existing_text == target_text
        )

        if tipe == "Transfer":

            if same_from and same_to:
                return row

        else:

            if same_platform and same_description:
                return row

    return None


