def format_bulan_ui(bulan):

    nama_bulan = [
        "Januari", "Februari", "Maret", "April",
        "Mei", "Juni", "Juli", "Agustus",
        "September", "Oktober", "November", "Desember"
    ]

    try:
        dt = datetime.strptime(bulan, "%Y-%m")
        return f"{nama_bulan[dt.month - 1]} {dt.year}"
    except:
        return bulan


def clean_date(value):

    if not value:
        return ""

    value = str(value).strip()

    # Jika AI memberi timestamp
    if " " in value:
        value = value.split(" ")[0]

    if "T" in value:
        value = value.split("T")[0]

    return value


